#!/usr/bin/env python3
"""Deterministic synthetic fixture generator for Agent Archivist.

Implements the Phase 0 deliverable "a deterministic synthetic fixture
generator; do not hand-copy real sessions" (docs/plan/plan.md, Section 8) and
produces the corpus categories the adapter-test contract names: normal,
large, malformed, partially written, and rewritten synthetic sessions
(plan Section 10, "Adapter tests"). Nothing in the corpus is copied from any
real harness store: every byte is derived from a closed vocabulary, fixed
identifier shapes, and a seeded deterministic bit generator.

Corpus layout under ``fixtures/synthetic`` (plan Section 6)::

    sessions/    normal complete sessions, plus additive-fields.jsonl
                 (forward-compat optional fields) and truncated-life.jsonl
                 (valid records, session never ended)
    rewritten/   per session, generation snapshots gen-000N.jsonl whose
                 earlier lines are byte-identical to the previous generation,
                 followed by a compaction record and fresh records
    large/       marathon/ (one month-scale session) and history/
                 (several synthetic accounts, many sessions each)
    malformed/   one file per defect, tagged in the manifest
    manifest.json  schema, seed, shape parameters, per-file digests

Determinism model:

1. The only entropy source is a SHA-256 counter-mode DRBG keyed by the
   recorded seed string. No clock, environment, locale, hostname, or
   ``random`` module is involved; newline is always ``\\n`` and timestamps
   are rendered from integer arithmetic, so regeneration is byte-identical
   across platforms and Python versions.
2. The committed ``manifest.json`` records the schema string, the seed, the
   corpus shape parameters, and one SHA-256 digest per file. ``--verify``
   regenerates the corpus from the manifest seed with the current code and
   byte-compares every file against the working tree, so any drift between
   code, corpus, and manifest fails the gate.
3. Changing the vocabulary, record shapes, or corpus counts changes the
   regenerated bytes; the workflow is then to rerun ``--generate``, and
   commit the corpus, manifest, and code together.

Content safety — the acceptance property is that scans find no private
transcript, credential, path, hostname, or account identifier. That is
enforced constructively and then verified:

1. Constructively: record text is drawn from a fixed word list, identifiers
   are UUIDv4-shaped, ``acct-``+hex, ``proj-word-word``, or
   ``synthetic-word-NNN`` labels, timestamps are integers over a fixed
   window, and the serializer emits no ``/`` or ``@`` byte anywhere, so no
   path, URL, email, or handle can appear.
2. By scan (``--verify``): every ASCII letter run must be a closed-vocabulary
   or structural token (pure ``a-f`` runs are permitted as artifacts of
   synthetic hex identifiers); parseable lines must contain only allowlisted
   keys and string values matching the synthetic shapes; raw ``/`` and ``@``
   bytes, an infrastructure denylist, and credential-shape markers must be
   absent.

Output safety: findings name the rule, file, and line only, never the
matched bytes — the same redaction ethos as the secret-scan lanes. On any
failure the tool prints a report to stderr and exits 2; on success it prints
a content-free summary (counts, bytes, digests) and exits 0.

Usage::

    tools/fixturegen.py --verify              # gate: regenerate, byte-compare, scan
    tools/fixturegen.py --generate OUTPUT     # write corpus + manifest to OUTPUT
    tools/fixturegen.py --generate OUTPUT --seed SEED   # non-canonical seed

``--generate`` refuses to overwrite an output directory that is not the
canonical corpus location unless ``--force`` is given, guarding against
accidentally clobbering an unrelated tree. Standard-library only, so a clean
checkout can run it before any dependency is fetched.
"""

