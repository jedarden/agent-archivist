/// Every scenario: the envelope-validation outcome matches the pinned
/// expectation, and every identity and object key re-derived from the
/// envelope's own inputs equals the manifest's `identity` block — including
/// the envelopes the validator itself rejects, whose inputs still derive.
#[test]
fn scenarios_replay_envelope_outcomes_and_identities() {
    let root = corpus_root();
    let manifest = load_json(&root, "manifest.json").unwrap();
    let mut failures = Vec::new();

    for scenario in scenarios(&manifest).unwrap() {
        let id = text(scenario, "manifest.json", "id").unwrap();
        let rel = format!("scenario {id}");
        let files = member(scenario, &rel, "files").unwrap();
        let envelope_rel = text(files, &rel, "envelope").unwrap();
        let envelope_bytes = read(&root, envelope_rel).unwrap();

        // The identity block holds derivations of the envelope's own inputs
        // regardless of the validation outcome.
        let envelope_value = json::parse(&envelope_bytes)
            .map_err(|e| format!("{envelope_rel}: {e}"))
            .unwrap();
        let inputs = match IdentityInputs::from_envelope_value(&envelope_value, envelope_rel) {
            Ok(inputs) => inputs,
            Err(e) => {
                failures.push(e);
                continue;
            }
        };
        let identity = identity_block(scenario, id).unwrap();
        assert_identity_block(&inputs, identity, &rel, &mut failures);

        // The validation outcome: an `envelope.*` error code is this crate's
        // rejection; anything else fails in a later layer (auth, storage) and
        // the envelope itself must parse.
        let expect = member(scenario, &rel, "expect").unwrap();
        let expected_code = text_member(expect, "error_code");
        match Envelope::parse(&envelope_bytes) {
            Ok(envelope) => {
                if let Some(code) = expected_code
                    && code.starts_with("envelope.")
                {
                    failures.push(format!(
                        "{rel}: envelope parsed but {code} is pinned: {envelope:?}"
                    ));
                }
                // The typed envelope agrees with the raw-input derivations.
                demand(
                    &mut failures,
                    format!("{rel}: session hash disagrees with the identity block"),
                    envelope.rederive_session_hash().to_hex()
                        == text(identity, &rel, "session_hash").unwrap(),
                );
                demand(
                    &mut failures,
                    format!("{rel}: occurrence disagrees with the identity block"),
                    envelope.rederive_occurrence_id().to_hex()
                        == text(identity, &rel, "occurrence_id").unwrap(),
                );
                demand(
                    &mut failures,
                    format!("{rel}: attestation disagrees with the identity block"),
                    envelope.rederive_attestation_id().to_hex()
                        == text(identity, &rel, "attestation_id").unwrap(),
                );
                // Wire-canonical scenarios hold their exact bytes.
                if boolean(scenario, &rel, "envelope_wire_canonical").unwrap() {
                    demand(
                        &mut failures,
                        format!("{rel}: envelope file is not the canonical bytes"),
                        envelope.canonical_bytes() == envelope_bytes,
                    );
                }
            }
            Err(error) => match expected_code {
                Some(code) if code == error.code().as_str() => {}
                Some(code) => failures.push(format!(
                    "{rel}: envelope rejected as {}, {code} pinned",
                    error.code().as_str()
                )),
                None => failures.push(format!(
                    "{rel}: envelope rejected as {} but no envelope rejection is pinned",
                    error.code().as_str()
                )),
            },
        }
    }

    assert!(
        failures.is_empty(),
        "{} scenario identity failures:\n  {}",
        failures.len(),
        failures.join("\n  ")
    );
}

/// Every scenario's transmitted bytes and attempt record: the request-body
/// digest the signature covers, the payload coupling, the signing preimage
/// and its digest, and the error/receipt records' pinned shapes.
#[test]
fn scenarios_attempt_records_and_transmitted_bytes_replay() {
    let root = corpus_root();
    let manifest = load_json(&root, "manifest.json").unwrap();
    let mut failures = Vec::new();

    for scenario in scenarios(&manifest).unwrap() {
        let id = text(scenario, "manifest.json", "id").unwrap();
        let rel = format!("scenario {id}");
        let files = member(scenario, &rel, "files").unwrap();
        let attempt_rel = text(files, &rel, "attempt").unwrap().to_owned();
        let attempt = load_json(&root, &attempt_rel).unwrap();
        let body_rel = text(files, &rel, "request_body").unwrap();
        let body = read(&root, body_rel).unwrap();
        let signing = member(scenario, &rel, "signing").unwrap();
        let identity = identity_block(scenario, id).unwrap();

        // The covered request digest: over the pristine signed body. The two
        // in-transit tamper scenarios pin the pristine digest separately and
        // their transmitted body must genuinely differ from it.
        let covered = text(&attempt, &attempt_rel, "request_content_digest").unwrap();
        if let Some(pristine) = text_member(signing, "signed_body_sha256") {
            demand(
                &mut failures,
                format!("{rel}: covered digest {covered} != pinned pristine {pristine}"),
                covered == pristine,
            );
            demand(
                &mut failures,
                format!("{rel}: transmitted body equals the pristine signed body"),
                sha256_hex(&body) != covered,
            );
        } else {
            demand(
                &mut failures,
                format!(
                    "{rel}: request body digest {} computed, {covered} covered",
                    sha256_hex(&body)
                ),
                sha256_hex(&body) == covered,
            );
        }

        // Identity transport: the canonical and transported payload digests
        // agree and equal the occurrence's blob digest.
        let canonical = text(&attempt, &attempt_rel, "payload_canonical_digest").unwrap();
        let transported = text(&attempt, &rel, "payload_transport_digest").unwrap();
        demand(
            &mut failures,
            format!("{rel}: canonical and transported payload digests disagree"),
            canonical == transported,
        );
        demand(
            &mut failures,
            format!("{rel}: payload digest != identity blob_digest"),
            canonical == text(identity, &rel, "blob_digest").unwrap(),
        );
        // An untampered scenario's payload part hashes to the blob digest.
        if optional(signing, "signed_body_sha256").is_none() {
            let payload_rel = text(files, &rel, "payload").unwrap();
            let payload = read(&root, payload_rel).unwrap();
            demand(
                &mut failures,
                format!(
                    "{rel}: payload part digest {} computed, {canonical} pinned",
                    sha256_hex(&payload)
                ),
                sha256_hex(&payload) == canonical,
            );
        }

        // The envelope digest covers the envelope's canonical bytes.
        let envelope_rel = text(files, &rel, "envelope").unwrap();
        let envelope_value = load_json(&root, envelope_rel).unwrap();
        demand(
            &mut failures,
            format!("{rel}: envelope digest disagrees with canonical bytes"),
            sha256_hex(&envelope_value.canonical_bytes())
                == text(&attempt, &attempt_rel, "envelope_digest").unwrap(),
        );

        // The signing preimage and its digest.
        let input = signing_input_from_attempt(&attempt, &attempt_rel).unwrap();
        demand(
            &mut failures,
            format!("{rel}: signing input disagrees with the pinned preimage"),
            hex(&input) == text(signing, &rel, "attempt_input_hex").unwrap(),
        );
        demand(
            &mut failures,
            format!("{rel}: signing input digest disagrees"),
            sha256_hex(&input) == text(signing, &rel, "attempt_input_sha256").unwrap(),
        );

        // The error or receipt record matches the pinned expectation.
        let expect = member(scenario, &rel, "expect").unwrap();
        check_outcome_records(&root, expect, identity, &rel, files, &mut failures);
    }

    assert!(
        failures.is_empty(),
        "{} scenario byte failures:\n  {}",
        failures.len(),
        failures.join("\n  ")
    );
}

/// One scenario's error and receipt records: the error record's code and
/// retryability match the pinned expectation, and the receipt's identity and
/// outcome members agree with the manifest's identity block and outcomes.
fn check_outcome_records(
    root: &Path,
    expect: &Value,
    identity: &Value,
    rel: &str,
    files: &Value,
    failures: &mut Vec<String>,
) {
    if let Some(error_rel) = text_member(files, "error") {
        let error = load_json(root, error_rel).unwrap();
        demand(
            failures,
            format!("{rel}: error record code disagrees"),
            text(&error, error_rel, "code").unwrap() == text(expect, rel, "error_code").unwrap(),
        );
        demand(
            failures,
            format!("{rel}: error record retryability disagrees"),
            boolean(&error, error_rel, "retryable").unwrap()
                == boolean(expect, rel, "retryable").unwrap(),
        );
    }
    if let Some(receipt_rel) = text_member(files, "receipt") {
        let receipt = load_json(root, receipt_rel).unwrap();
        for field in [
            "occurrence_id",
            "attestation_id",
            "blob_digest",
            "blob_object_key",
            "occurrence_object_key",
            "attestation_object_key",
        ] {
            demand(
                failures,
                format!("{rel}: receipt {field} disagrees with the identity block"),
                text(&receipt, receipt_rel, field).unwrap() == text(identity, rel, field).unwrap(),
            );
        }
        if let Some(outcomes) = optional(expect, "outcomes") {
            for (outcome, member_name) in [
                ("attestation", "attestation_outcome"),
                ("blob", "blob_outcome"),
                ("occurrence", "occurrence_outcome"),
            ] {
                demand(
                    failures,
                    format!("{rel}: receipt {member_name} disagrees"),
                    text(&receipt, receipt_rel, member_name).unwrap()
                        == text(outcomes, rel, outcome).unwrap(),
                );
            }
        }
    }
}

/// One named scenario's envelope member, canonicalized for comparison.
/// `None` when the member is absent.
fn envelope_member_bytes(root: &Path, manifest: &Value, id: &str, field: &str) -> Option<Vec<u8>> {
    let scenario = scenarios(manifest)
        .unwrap()
        .iter()
        .find(|s| text(s, "manifest.json", "id").unwrap() == id)?;
    let files = member(scenario, "manifest.json", "files").unwrap();
    let envelope_rel = text(files, "manifest.json", "envelope").unwrap();
    let envelope = load_json(root, envelope_rel).unwrap();
    optional(&envelope, field).map(Value::canonical_bytes)
}

/// The manifest's cross-scenario invariants: relay convergence, cross-tenant
/// separation, and retry identity equality, checked against the identities
/// the manifest itself pins for the named scenarios.
#[test]
fn manifest_invariants_hold_across_their_scenarios() {
    let root = corpus_root();
    let manifest = load_json(&root, "manifest.json").unwrap();
    let invariants = member(&manifest, "manifest.json", "invariants").unwrap();
    let mut failures = Vec::new();

    let identity_of = |id: &str| -> Value {
        let scenario = scenarios(&manifest)
            .unwrap()
            .iter()
            .find(|s| text(s, "manifest.json", "id").unwrap() == id)
            .unwrap_or_else(|| panic!("manifest.json: scenario {id} is missing"));
        identity_block(scenario, id).unwrap().clone()
    };
    let scenario_ids = |invariant: &str| -> Vec<String> {
        array(
            member(invariants, "manifest.json", invariant).unwrap(),
            "manifest.json",
            "scenarios",
        )
        .unwrap()
        .iter()
        .map(|v| {
            let Value::Text(id) = v else {
                panic!("manifest.json: {invariant} scenario id is not a string");
            };
            id.clone()
        })
        .collect()
    };

    // One blob key and one occurrence key serve both uploaders, with two
    // attestation keys beside them (EC-05A, STO-013).
    let relay = member(invariants, "manifest.json", "relay_occurrence_equality").unwrap();
    let shared = member(relay, "manifest.json", "shared").unwrap();
    let pair = scenario_ids("relay_occurrence_equality");
    let direct = identity_of(&pair[0]);
    let relayed = identity_of(&pair[1]);
    for (identity, name) in [(&direct, "direct"), (&relayed, "relay")] {
        for field in ["blob_object_key", "occurrence_object_key"] {
            demand(
                &mut failures,
                format!("relay equality: {name} {field} is not the shared key"),
                text(identity, name, field).unwrap()
                    == text(shared, "manifest.json", field).unwrap(),
            );
        }
    }
    demand(
        &mut failures,
        "relay equality: relay attestation key is not the pinned one".to_owned(),
        text(&relayed, "relay", "attestation_object_key").unwrap()
            == text(shared, "manifest.json", "relay_attestation_object_key").unwrap(),
    );
    demand(
        &mut failures,
        "relay equality: both attestation keys are the same".to_owned(),
        text(&direct, "direct", "attestation_object_key").unwrap()
            != text(&relayed, "relay", "attestation_object_key").unwrap(),
    );

    // Tenant is the only changed identity input: session hashes diverge while
    // the blob digest is shared (EC-03, STO-002).
    let pair = scenario_ids("cross_tenant_separation");
    let first = identity_of(&pair[0]);
    let second = identity_of(&pair[1]);
    demand(
        &mut failures,
        "cross-tenant: session hashes are not distinct".to_owned(),
        text(&first, "first", "session_hash").unwrap()
            != text(&second, "second", "session_hash").unwrap(),
    );
    demand(
        &mut failures,
        "cross-tenant: blob digest is not shared".to_owned(),
        text(&first, "first", "blob_digest").unwrap()
            == text(&second, "second", "blob_digest").unwrap(),
    );

    // The frozen envelope across a retry (STO-004): a field named by
    // `identical_fields` compares from the identity block when present and
    // from the envelopes themselves otherwise (`request_id` is an envelope
    // member) — the rule the generator's --verify and the standalone
    // contract verifier both pin.
    let retry = member(invariants, "manifest.json", "retry_identity_equality").unwrap();
    let pair = scenario_ids("retry_identity_equality");
    let first = identity_of(&pair[0]);
    let second = identity_of(&pair[1]);
    for field in array(retry, "manifest.json", "identical_fields").unwrap() {
        let Value::Text(field) = field else {
            failures.push("manifest.json: retry identical_fields entry is not a string".into());
            continue;
        };
        let same = if optional(&first, field).is_some() {
            text(&first, "first", field).unwrap() == text(&second, "second", field).unwrap()
        } else {
            envelope_member_bytes(&root, &manifest, &pair[0], field).unwrap()
                == envelope_member_bytes(&root, &manifest, &pair[1], field).unwrap()
        };
        demand(
            &mut failures,
            format!("retry equality: {field} differs across the pair"),
            same,
        );
    }

    assert!(
        failures.is_empty(),
        "{} invariant failures:\n  {}",
        failures.len(),
        failures.join("\n  ")
    );
}
