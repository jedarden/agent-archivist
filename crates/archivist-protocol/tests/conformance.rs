//! Integration replay of the language-neutral conformance corpus
//! (`schemas/v1/examples/conformance`; plan Sections 7.1–7.5 and 8).
//!
//! Where [`archivist_protocol::json`] is used to read the corpus files, the
//! crate's own owned parser is the reader — the bead's no-new-dependencies
//! rule — and every assertion compares bytes, not re-serialized text: the
//! canonical forms, digests, identifiers, object keys, and signing preimages
//! this crate computes from each vector's own inputs must equal the pinned
//! golden exactly or the vector's name appears in the failure.
//!
//! The corpus is generated by `tools/conformancegen.py`; this file asserts
//! the *Rust* side of the language-neutral contract (the generator's own
//! `--verify` and the standalone `tools/contract-verifier.py` cover the
//! generator and the cross-implementation comparison). Layers beyond the
//! protocol crate — Ed25519 verification, the receipt chain, authorization
//! windows — are pinned by those tools and live in `archivist-auth`.

